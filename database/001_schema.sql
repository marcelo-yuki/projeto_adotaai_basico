-- Execute em um projeto Supabase NOVO (PostgreSQL).
create extension if not exists pgcrypto;
create table public.perfis (
 id uuid primary key references auth.users(id) on delete cascade,
 email text not null, telefone text, tipo text not null default 'adotante' check (tipo in ('adotante','colaborador')),
 criado_em timestamptz not null default now()
);
create table public.questionarios (
 adotante_id uuid primary key references public.perfis(id) on delete cascade,
 especie text check (especie in ('cão','gato','')),
 porte text check (porte in ('pequeno','médio','grande','')),
 idade text check (idade in ('filhote','adulto','idoso','')),
 moradia text check (moradia in ('apartamento','casa','casa_quintal')),
 atividade text check (atividade in ('sedentario','moderado','ativo')),
 rotina text check (rotina in ('pouco_tempo','medio_tempo','muito_tempo')),
 tem_criancas boolean not null default false,
 tem_outros_pets boolean not null default false,
 aceita_especiais boolean not null default false,
 atualizado_em timestamptz not null default now()
);
create table public.animais (
 id bigint generated by default as identity primary key,
 nome text not null, sexo text, especie text not null check (especie in ('cão','gato')),
 nascimento date, idade_descritiva text, porte text check (porte in ('pequeno','médio','grande')),
 raca text, cidade text, imagem_url text, descricao text, historico text, informacoes_medicas text,
 castrado boolean not null default false, necessidade_especial boolean not null default false,
 pet_unico boolean not null default false, finalidade text,
 status text not null default 'disponivel' check (status in ('disponivel','em_processo','adotado')),
 criado_por uuid references public.perfis(id) on delete set null,
 criado_em timestamptz not null default now()
);
create table public.colaboradores_animais (
 colaborador_id uuid not null references public.perfis(id) on delete cascade,
 animal_id bigint not null references public.animais(id) on delete cascade,
 primary key(colaborador_id,animal_id)
);
create table public.animais_curtidos (
 adotante_id uuid not null references public.perfis(id) on delete cascade,
 animal_id bigint not null references public.animais(id) on delete cascade,
 criado_em timestamptz not null default now(),
 primary key(adotante_id,animal_id)
);
create table public.interesses (
 id bigint generated always as identity primary key,
 adotante_id uuid not null references public.perfis(id) on delete cascade,
 animal_id bigint not null references public.animais(id) on delete cascade,
 status text not null default 'pendente' check(status in ('pendente','em_analise','aprovado','recusado','cancelado')),
 criado_em timestamptz not null default now(), unique(adotante_id,animal_id)
);
create table public.mensagens (
 id bigint generated always as identity primary key,
 interesse_id bigint not null references public.interesses(id) on delete cascade,
 remetente_id uuid not null references public.perfis(id) on delete cascade,
 conteudo text not null check(length(trim(conteudo)) between 1 and 5000),
 criado_em timestamptz not null default now()
);
create index idx_animais_status on public.animais(status);
create index idx_interesses_animal on public.interesses(animal_id);
create index idx_mensagens_interesse on public.mensagens(interesse_id, criado_em);
create index idx_vinculos_animal on public.colaboradores_animais(animal_id);
